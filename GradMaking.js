

let grad = 32;

if(grad >= 80 && grad <= 100){
    console.log("A+");
}
else if(grad >= 70 && grad < 80){
    console.log("A");
}
else if(grad >= 60 && grad < 70){
    console.log("B");
}
else if(grad >= 50 && grad < 60){
    console.log("C");
}
else if(grad >= 40 && grad < 50){
    console.log("D");
}
else if(grad >= 33 && grad < 40){
    console.log("E");
}
else{
    console.log("Fail");
}
